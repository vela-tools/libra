#![expect(clippy::unwrap_used, reason = "panicking is how a test harness reports a failure")]

//! Properties the evaluator has to hold for every policy set, not just the ones somebody wrote a
//! test for.
//!
//! The example-based tests next to the implementation say what happens for the cases their author
//! thought of. These say what must be true of all of them, which is the part a policy engine on an
//! authorization boundary needs: a decision that depends on the order a directory happened to be
//! read in, or a deny that can be argued out of by adding more policies, is a defect an example
//! test only finds if it happens to generate the example.

use jiff::Timestamp;
use libra_jsonld_term_expansion::name::ExpandedIri;
use libra_policy_engine::{
    engine::evaluate,
    request::{EvaluationRequest, RequestedTypes},
};
use libra_policy_model::{
    access::CompiledAccess,
    attribute::{AttributeAction, CompiledAttributeRestriction},
    condition::CompiledCondition,
    effect::Effect,
    identity::{IdentityName, TenantSelector, Username},
    operation::Operation,
    policy::{CompiledPolicy, PolicyId},
    resource_family::ResourceFamily,
};
use libra_policy_store::snapshot::PolicySnapshot;
use proptest::{collection::vec, option::of, prelude::*};
use std::sync::Arc;

/// The callers the generated policies are written about.
const USERS: [&str; 3] = ["alice", "bob", "carol"];

/// The attributes the generated restrictions are written about.
const ATTRIBUTES: [&str; 3] = [
    "https://example.test/ns#speed",
    "https://example.test/ns#brand",
    "https://example.test/ns#location",
];

/// A policy before it is turned into a [`CompiledPolicy`], generated by index rather than by value
/// so the search space stays small enough for the shrinker to be useful.
#[derive(Debug, Clone)]
struct Generated {
    priority: u32,
    effect: Effect,
    /// Indices into [`USERS`], or `None` for a policy that applies to everyone.
    users: Option<Vec<usize>>,
    /// An attribute restriction, as an action and indices into [`ATTRIBUTES`].
    attribute: Option<(AttributeAction, Vec<usize>)>,
}

/// Turns a generated policy into the compiled form the evaluator reads.
fn compile(index: usize, generated: &Generated) -> CompiledPolicy {
    let users = generated.users.as_ref().map(|chosen| chosen.iter().map(|&user| username(user)).collect());

    let attribute = generated
        .attribute
        .as_ref()
        .map(|(action, chosen)| CompiledAttributeRestriction::new(*action, chosen.iter().map(|&attribute| ExpandedIri::new(ATTRIBUTES[attribute])).collect()));

    CompiledPolicy {
        id: PolicyId::new(format!("generated-{index}")).unwrap(),
        description: String::new(),
        priority: generated.priority,
        condition: CompiledCondition {
            callers: None,
            users,
            principals: None,
            groups: None,
            roles: None,
            tenants: None,
            operations: None,
            resources: None,
            entity_types: None,
            queries: None,
            time_interval: None,
        },
        access: CompiledAccess {
            effect: generated.effect,
            scope: None,
            entity_type: None,
            time: None,
            attribute: attribute.map(Arc::new),
            aggregation: None,
        },
    }
}

/// A snapshot of the generated policies, in the order they were generated.
fn snapshot(generated: &[Generated], default_effect: Effect) -> PolicySnapshot {
    PolicySnapshot::new(
        generated.iter().enumerate().map(|(index, policy)| compile(index, policy)).collect(),
        default_effect,
    )
}

/// The caller `USERS[index]` names.
fn username(index: usize) -> Username {
    Username::new(USERS[index]).unwrap()
}

/// The account `USERS[index]` names, as a request carries it.
fn account(index: usize) -> IdentityName {
    IdentityName::Account(username(index))
}

/// The request every property is evaluated against.
const fn request<'a>(caller: &'a IdentityName, tenant: &'a TenantSelector, now: Timestamp) -> EvaluationRequest<'a> {
    EvaluationRequest {
        name: Some(caller),
        groups: &[],
        roles: &[],
        tenant,
        operation: Operation::Read,
        resource: ResourceFamily::Entities,
        entity_types: RequestedTypes::Unbounded,
        query: None,
        now,
    }
}

fn effect() -> impl Strategy<Value = Effect> {
    prop_oneof![Just(Effect::Allow), Just(Effect::Deny)]
}

fn action() -> impl Strategy<Value = AttributeAction> {
    prop_oneof![Just(AttributeAction::Pick), Just(AttributeAction::Omit)]
}

fn policy() -> impl Strategy<Value = Generated> {
    (
        0_u32..4,
        effect(),
        of(vec(0_usize..USERS.len(), 1..=USERS.len())),
        of((action(), vec(0_usize..ATTRIBUTES.len(), 1..=ATTRIBUTES.len()))),
    )
        .prop_map(|(priority, effect, users, attribute)| Generated {
            priority,
            effect,
            users,
            attribute,
        })
}

fn policies() -> impl Strategy<Value = Vec<Generated>> {
    vec(policy(), 0..6)
}

proptest! {
    /// The order a directory is read in is not part of the security model.
    #[test]
    fn the_order_policies_arrive_in_never_changes_the_decision(generated in policies(), user in 0_usize..USERS.len()) {
        let tenant = TenantSelector::Untenanted;
        let now = Timestamp::now();
        // Each policy keeps its identifier in either order: the identifier breaks ties, so numbering
        // the reversed list afresh would be a different policy set rather than the same one reordered.
        let compiled: Vec<CompiledPolicy> = generated.iter().enumerate().map(|(index, policy)| compile(index, policy)).collect();
        let mut reversed = compiled.clone(); // both orders are evaluated
        reversed.reverse();

        let forwards = evaluate(&PolicySnapshot::new(compiled, Effect::Deny), &request(&account(user), &tenant, now));
        let backwards = evaluate(&PolicySnapshot::new(reversed, Effect::Deny), &request(&account(user), &tenant, now));

        prop_assert_eq!(forwards.effect, backwards.effect);
        prop_assert_eq!(forwards.attribute, backwards.attribute);
    }

    /// A refusal cannot be argued out of by adding policies below it.
    #[test]
    fn a_deny_above_everything_always_refuses(mut generated in policies(), user in 0_usize..USERS.len()) {
        generated.push(Generated { priority: 9, effect: Effect::Deny, users: None, attribute: None });
        let tenant = TenantSelector::Untenanted;

        let decision = evaluate(&snapshot(&generated, Effect::Allow), &request(&account(user), &tenant, Timestamp::now()));

        prop_assert_eq!(decision.effect, Effect::Deny);
        prop_assert!(decision.attribute.is_none(), "a refusal carries no restrictions, because there is nothing to restrict");
    }

    /// Whatever a policy that cannot apply says, it says it about somebody else.
    #[test]
    fn a_policy_that_cannot_match_changes_nothing(generated in policies(), user in 0_usize..USERS.len()) {
        let tenant = TenantSelector::Untenanted;
        let now = Timestamp::now();
        let before = evaluate(&snapshot(&generated, Effect::Deny), &request(&account(user), &tenant, now));

        let mut with_irrelevant = generated;
        // Conditioned on the users this request is not, at the highest priority in play.
        with_irrelevant.push(Generated {
            priority: 9,
            effect: Effect::Allow,
            users: Some((0..USERS.len()).filter(|&other| other != user).collect()),
            attribute: None,
        });
        let after = evaluate(&snapshot(&with_irrelevant, Effect::Deny), &request(&account(user), &tenant, now));

        prop_assert_eq!(before.effect, after.effect);
        prop_assert_eq!(before.attribute, after.attribute);
    }

    /// The strongest matching allow alone says which attributes are exposed; nothing below it widens
    /// or narrows that.
    #[test]
    fn only_the_winning_allow_shapes_the_attributes(
        generated in policies(),
        user in 0_usize..USERS.len(),
        winner in of((action(), vec(0_usize..ATTRIBUTES.len(), 1..=ATTRIBUTES.len()))),
    ) {
        let mut with_winner = generated;
        // Above every generated priority, and matching every caller.
        with_winner.push(Generated { priority: 9, effect: Effect::Allow, users: None, attribute: winner });
        let expected = compile(with_winner.len() - 1, &with_winner[with_winner.len() - 1]).access.attribute;

        let tenant = TenantSelector::Untenanted;
        let decision = evaluate(&snapshot(&with_winner, Effect::Deny), &request(&account(user), &tenant, Timestamp::now()));

        prop_assert_eq!(decision.effect, Effect::Allow);
        prop_assert_eq!(decision.attribute, expected);
    }

    /// Nothing matching is a decision too, and it is the configured one.
    #[test]
    fn a_request_nothing_matches_takes_the_default_effect(default in effect(), user in 0_usize..USERS.len()) {
        // Every policy is about somebody else.
        let generated: Vec<Generated> = (0..USERS.len())
            .filter(|&other| other != user)
            .map(|other| Generated { priority: 5, effect: Effect::Allow, users: Some(vec![other]), attribute: None })
            .collect();

        let tenant = TenantSelector::Untenanted;
        let decision = evaluate(&snapshot(&generated, default), &request(&account(user), &tenant, Timestamp::now()));

        prop_assert_eq!(decision.effect, default);
        prop_assert!(decision.matched.is_none(), "the default effect is not a policy and must not be reported as one");
    }
}
